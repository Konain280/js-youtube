switch(day){
    case "Monday is a good day":
        console.log("Start of the work week");
        break;      
    case "Tuesday":
        console.log("Second day of the work week");
        break;
    case "Wednesday":
        console.log("Midweek day");
        break;
    case "Thursday":
        console.log("Fourth day of the work week");
        break;
    case "Friday":
        console.log("Last day of the work week");
        break;
    case "Saturday":
        console.log("Weekend day");
        break;
    case "Sunday":
        console.log("Weekend day");
        break;
    default:
        console.log("Invalid day");
}
